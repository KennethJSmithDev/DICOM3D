import assert from 'node:assert/strict';
import {beginnerLesson} from './src/beginner-learning.mjs';
import {buildLearnContext} from './src/learn-context.mjs';
const lesson=options=>beginnerLesson(options,buildLearnContext(options));
const body=result=>result.ideas.map(item=>item.body).join(' ');
let result=lesson({});
assert.equal(result.title,'Explore the human body');
assert.ok(result.actions.some(a=>a.id==='select-example'));
assert.ok(result.check.explanation.includes('does not establish'));
const index={structures:[{id:'FMA7309',label:'Right Lung',bundleId:'thorax',systems:['Respiratory system']}],hierarchy:[]};
const base={index,selected:'FMA7309',bundles:new Map([['thorax',{manifest:{reference:{id:'male'}}}]])};
result=lesson(base);
assert.match(body(result),/oxygen/);
assert.match(body(result),/Respiratory system/);
assert.match(body(result),/source shape may show only part/);
assert.equal(result.links[0].href,'https://www.nhlbi.nih.gov/health/lungs');
assert.ok(result.actions.some(a=>a.id==='focus-selection'));
assert.match(body(lesson({...base,bundles:new Map()})),/not loaded yet/);
assert.match(body(lesson({...base,isolatedId:'FMA7309'})),/Restore the reference/);
assert.match(body(lesson({...base,opacity:0.25})),/Transparency is already reduced/);
assert.match(body(lesson({...base,appearance:'holographic'})),/look luminous/);
// A name alone cannot establish an anatomical identity or supply a whole-organ lesson.
result=lesson({index:{structures:[{id:'unverified',label:'Right Lung'}]},selected:'unverified'});
assert.doesNotMatch(body(result),/oxygen/);
result=lesson({...base,femaleActive:true,femaleSelected:'capsule',femaleData:{index:{structures:[{id:'capsule',label:'Kidney capsule'}],held:[]},manifest:{}}});
assert.match(body(result),/female reference/);
assert.match(body(result),/not necessarily a complete organ/);
assert.doesNotMatch(body(result),/oxygen/);
assert.notEqual(result.key,lesson(base).key);
const study={binding:{frames:[{ct_k:5,nonzero_voxels:0},{ct_k:6,nonzero_voxels:5}]}};
result=lesson({studyView:true,study,studyFrame:5});
assert.match(body(result),/does not cross this picture/);
assert.match(body(result),/picture 6/);
assert.ok(result.actions.some(a=>a.id==='next-frame'));
result=lesson({studyView:true,study,studyFrame:6,studySeg:false,wipe:true});
assert.match(body(result),/switched off/);
assert.match(body(result),/does not prove/);
assert.notEqual(result.key,lesson({studyView:true,study,studyFrame:5}).key);
result=lesson({localMode:true,localStudy:{descriptor:{shape:[50,256,256],PatientName:'DO_NOT_LEAK',Report:'SECRET_DIAGNOSIS'}},study,studyFrame:6,localFrame:1,showStack:true});
assert.match(body(result),/stack of pictures/);
assert.match(body(result),/no supplied organ or finding segmentation/);
assert.doesNotMatch(JSON.stringify(result),/DO_NOT_LEAK|SECRET_DIAGNOSIS|colored area follows/);
assert.ok(result.links.some(l=>l.href.startsWith('https://www.nibib.nih.gov/')));
result=lesson({imagingOpen:true});
assert.ok(result.actions.some(a=>a.id==='open-imaging'));
assert.match(result.title,/Start with a scan/);
result=lesson({nrx:true});
assert.match(body(result),/not reconstructed from the scan/);
console.log('PASS: beginner learning context adaptation, exact-ID education, female scope, loaded/unloaded guidance, presentation state, CT/SEG correspondence, local privacy, source links and self-check boundaries.');
